import { readFileSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { DetectorContext, UnshitConfig } from '../contracts.js';
import { DEFAULT_CONFIG } from '../config.js';
import { basenameOf, normalizeRelPath, toSegments } from './project-paths.js';
import inferShape, { type ProjectShape } from './project-shape.js';

const CONTEXT_START_MARKER = '<!-- unshit:context:start -->';
const CONTEXT_END_MARKER = '<!-- unshit:context:end -->';
const TARGET_FILE_NAME = 'AGENTS.md';
const VERIFY_SCRIPT_KEYS = ['typecheck', 'test', 'lint', 'build'] as const;

interface AgentRule {
  ruleId: string;
  note: string;
}

interface PackageJsonScripts {
  scripts?: unknown;
}

function nonEmpty(values: string[]): string[] {
  return values.filter((value) => value.length > 0);
}

function packageJsonText(ctx: DetectorContext): string | undefined {
  const loaded = ctx.files.find((file) => basenameOf(normalizeRelPath(file.relPath)) === 'package.json');
  if (loaded?.content) return loaded.content;
  const relPath = (ctx.manifests ?? []).find((manifest) => basenameOf(normalizeRelPath(manifest)) === 'package.json');
  if (!relPath) return undefined;
  try {
    return readFileSync(join(ctx.rootDir, ...toSegments(relPath)), 'utf8');
  } catch {
    return undefined;
  }
}

function verifyCommands(ctx: DetectorContext): string[] {
  const text = packageJsonText(ctx);
  if (!text) return [];
  let scripts: unknown;
  try {
    scripts = (JSON.parse(text) as PackageJsonScripts).scripts;
  } catch {
    return [];
  }
  if (typeof scripts !== 'object' || scripts === null || Array.isArray(scripts)) return [];
  const entries = scripts as Record<string, unknown>;
  const found: string[] = [];
  for (const key of VERIFY_SCRIPT_KEYS) {
    const value = entries[key];
    if (typeof value === 'string' && value.trim().length > 0) found.push(value.trim());
  }
  return found;
}

function activeRules(config: UnshitConfig): AgentRule[] {
  const disabled = new Set(config.disabledRules);
  const candidates: AgentRule[] = [
    { ruleId: 'ts/no-explicit-any', note: 'no explicit `any` or `as any`' },
    { ruleId: 'ts/no-double-cast', note: 'no `as unknown as` type-system bypasses' },
    { ruleId: 'css/no-important', note: 'no `!important`' },
    {
      ruleId: 'react/god-file',
      note: `files ≤ ${config.godFileMaxLines} lines / ≤ ${config.godFileMaxHooks} hooks`,
    },
    { ruleId: 'code/high-complexity', note: `cognitive complexity ≤ ${config.complexityMax}` },
    { ruleId: 'code/duplicate-block', note: `token windows ≥ ${config.cloneMinTokens}` },
    { ruleId: 'ts/unused-export', note: 'no unused exports' },
  ];
  return candidates.filter((rule) => !disabled.has(rule.ruleId));
}

function architectureLines(config: UnshitConfig): string[] {
  const lines: string[] = [];
  for (const layer of config.layers ?? []) {
    const allows = layer.allowImportsFrom && layer.allowImportsFrom.length > 0
      ? ` — may import from: ${layer.allowImportsFrom.join(', ')}`
      : '';
    lines.push(`- Layer ${layer.name}${allows}`);
  }
  const structure = config.structure;
  if (structure) {
    const parts: string[] = [];
    if (structure.featureContainers && structure.featureContainers.length > 0) {
      parts.push(`feature containers: ${structure.featureContainers.join(', ')}`);
    }
    if (structure.tangleMinFiles !== undefined) {
      parts.push(`tangle min files: ${structure.tangleMinFiles}`);
    }
    const allow = nonEmpty(structure.allow ?? []);
    if (allow.length > 0) parts.push(`allow: ${allow.join(' | ')}`);
    if (parts.length > 0) lines.push(`- Structure rules: ${parts.join('; ')}`);
  }
  return lines;
}

function coreFactsLines(shape: ProjectShape): string[] {
  return [
    `- Archetype: ${shape.archetype}`,
    `- Layout: ${shape.layout}`,
    `- Source roots: ${nonEmpty(shape.sourceRoots).join(', ') || '(none)'}`,
    `- Packages: ${nonEmpty(shape.packages).join(', ') || '(none)'}`,
  ];
}

/**
 * Builds the deterministic "project rules" markdown block, including the
 * `<!-- unshit:context:start -->` / `<!-- unshit:context:end -->` markers.
 */
export function generateContextBlock(ctx: DetectorContext): string {
  const shape = inferShape(ctx);
  const config = ctx.config ?? DEFAULT_CONFIG;
  const lines = [
    '# Project rules (generated by `unshit context`)',
    '',
    ...coreFactsLines(shape),
  ];
  const verify = verifyCommands(ctx);
  if (verify.length > 0) lines.push(`- Verify: ${verify.join(' | ')}`);
  lines.push(...architectureLines(config));
  const rules = activeRules(config);
  if (rules.length > 0) {
    lines.push('- Unshit rules to obey:');
    for (const rule of rules) lines.push(`  - ${rule.ruleId} — ${rule.note}`);
  }
  const disabled = nonEmpty([...config.disabledRules].sort((a, b) => a.localeCompare(b)));
  if (disabled.length > 0) lines.push(`- Disabled: ${disabled.join(', ')}`);
  return [CONTEXT_START_MARKER, ...lines, CONTEXT_END_MARKER].join('\n');
}

function replaceBlock(existing: string, block: string): string {
  const startIdx = existing.indexOf(CONTEXT_START_MARKER);
  if (startIdx === -1) {
    return existing.length > 0 ? `${existing.replace(/\s+$/, '')}\n\n${block}` : block;
  }
  const endIdx = existing.indexOf(CONTEXT_END_MARKER, startIdx + CONTEXT_START_MARKER.length);
  if (endIdx === -1) {
    return existing.length > 0 ? `${existing.replace(/\s+$/, '')}\n\n${block}` : block;
  }
  return existing.slice(0, startIdx) + block + existing.slice(endIdx + CONTEXT_END_MARKER.length);
}

/**
 * Inserts or replaces the context block in `AGENTS.md` between the markers,
 * creating the file when missing and leaving all other content byte-identical.
 */
export async function writeContextBlock(
  rootDir: string,
  block: string,
  fileName = TARGET_FILE_NAME,
): Promise<{ fileName: string; created: boolean }> {
  const path = join(rootDir, fileName);
  let existing = '';
  let exists = true;
  try {
    existing = await readFile(path, 'utf8');
  } catch (err: unknown) {
    if ((err as { code?: string })?.code !== 'ENOENT') throw err;
    exists = false;
  }
  await writeFile(path, replaceBlock(existing, block), 'utf8');
  return { fileName, created: !exists };
}
